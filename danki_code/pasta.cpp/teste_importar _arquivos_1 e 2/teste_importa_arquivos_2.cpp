
using namespace std;
class Fruta{
    private:
    string fruta;
    float preco;
    public:
    Fruta(string frutaNova, float preco){
        fruta = frutaNova;
        preco = precoNovo;
    }
    string getfruta(){
        return fruta;
    }
    string getpreco(){
        return preco;
    }
    void setfruta(string frutaNova){
        fruta = frutaNova;
    }
    void setpreco(float precoNovo){
        preco = precoNovo;
    }
};